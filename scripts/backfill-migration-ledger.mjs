/**
 * Generate SQL that tells Drizzle which migrations are already applied.
 *
 * WHY THIS EXISTS
 *
 * Migrations here have been applied by hand — pasted into the Neon console
 * rather than run through `drizzle-kit migrate`. The schema is therefore
 * correct, but Drizzle's own ledger (`drizzle.__drizzle_migrations`) has no
 * record of it, so the tool still believes nothing has been applied.
 *
 * That matters because of how the skip decision actually works. From
 * `drizzle-orm/pg-core/dialect.js` (`PgDialect.migrate`):
 *
 *     select id, hash, created_at from drizzle.__drizzle_migrations
 *       order by created_at desc limit 1
 *     ...
 *     if (!lastDbMigration || Number(lastDbMigration.created_at) < migration.folderMillis)
 *
 * Two things follow, and both are the opposite of what the column names suggest:
 *
 *   1. Only the SINGLE most recent row is read. Drizzle does not diff the set of
 *      applied migrations — it takes one high-water mark and replays everything
 *      newer than it.
 *   2. The hash is WRITTEN but never READ BACK. It plays no part in deciding
 *      what to run. Editing an already-applied migration file will not be
 *      detected.
 *
 * So with an empty ledger, `npm run db:migrate` starts at
 * `0000_light_tana_nile.sql` — 28 statements, zero `IF NOT EXISTS` guards. It
 * aborts on `CREATE TABLE "users"` already existing, which means nothing gets
 * corrupted, but the command is unusable and every future migration has to be
 * pasted by hand forever.
 *
 * WHAT THIS EMITS
 *
 * One row per journal entry, each guarded by `WHERE NOT EXISTS`, so the script
 * is safe to run whether the ledger is empty, half-populated, or already
 * complete. Strictly, only the highest `created_at` is load-bearing; the full
 * set is written anyway so the table is an honest record rather than a single
 * sentinel, and so it still reads correctly if Drizzle ever moves to comparing
 * hashes.
 *
 * ON THE HASH AND LINE ENDINGS
 *
 * Drizzle hashes the raw file bytes as read from disk. This repo uses
 * `text=auto`, so the working tree is CRLF on Windows and LF on Linux — the
 * same migration hashes differently depending on the machine. Since the hash is
 * never compared, neither value breaks anything; LF is used here because that is
 * the canonical content in git, not one checkout's rendering of it.
 *
 * USAGE
 *
 *     node scripts/backfill-migration-ledger.mjs > backfill.sql
 *
 * Then run backfill.sql against the target database and delete it.
 */
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'drizzle');

const journal = JSON.parse(readFileSync(join(migrationsDir, 'meta', '_journal.json'), 'utf8'));

/** Drizzle's own defaults; `drizzle.config.ts` does not override them. */
const SCHEMA = 'drizzle';
const TABLE = '__drizzle_migrations';

const rows = journal.entries.map((entry) => {
  const sql = readFileSync(join(migrationsDir, `${entry.tag}.sql`), 'utf8').replace(/\r\n/g, '\n');
  return {
    tag: entry.tag,
    hash: createHash('sha256').update(sql).digest('hex'),
    createdAt: entry.when,
  };
});

const out = [];
out.push('-- Backfill Drizzle\'s migration ledger to match a hand-applied database.');
out.push('-- Generated by scripts/backfill-migration-ledger.mjs. Safe to re-run.');
out.push('--');
out.push(`-- ${rows.length} migrations, through ${rows[rows.length - 1].tag}.`);
out.push('');
out.push('BEGIN;');
out.push('');
out.push(`CREATE SCHEMA IF NOT EXISTS "${SCHEMA}";`);
out.push('');
// Column types copied from PgDialect.migrate so a table we create here is
// byte-identical to one Drizzle would have created itself.
out.push(`CREATE TABLE IF NOT EXISTS "${SCHEMA}"."${TABLE}" (`);
out.push('  id SERIAL PRIMARY KEY,');
out.push('  hash text NOT NULL,');
out.push('  created_at bigint');
out.push(');');
out.push('');

for (const row of rows) {
  out.push(`-- ${row.tag}`);
  out.push(`INSERT INTO "${SCHEMA}"."${TABLE}" ("hash", "created_at")`);
  out.push(`SELECT '${row.hash}', ${row.createdAt}`);
  out.push('WHERE NOT EXISTS (');
  out.push(`  SELECT 1 FROM "${SCHEMA}"."${TABLE}" WHERE "hash" = '${row.hash}'`);
  out.push(');');
  out.push('');
}

out.push('COMMIT;');
out.push('');

process.stdout.write(out.join('\n'));
